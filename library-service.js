'use strict';
/* Jam Fokus — Library file service (main process).
   Owns every managed file under <userData>/library/files. The renderer never
   sees real paths: it gets one-time tokens for picked files and refers to
   managed files only by validated names. Electron objects are injected so the
   whole service can be tested in plain Node with a temp directory. */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const MAX_BYTES = 25 * 1024 * 1024;
const MAX_PICK = 10;
const TOKEN_TTL_MS = 60000;
/* Types the app may import. Script/HTML types are intentionally NOT allowed here:
   "Buka" hands the file to the OS default app, which could run a .js (Windows Script
   Host) or render a .html. See BLOCKED_OPEN_EXT for files that were imported earlier. */
const ALLOWED_EXT = new Set([
  '.docx', '.xlsx', '.pptx', '.doc', '.xls', '.ppt', '.odt', '.ods', '.odp', '.rtf',
  '.pdf', '.png', '.jpg', '.jpeg', '.gif', '.webp',
  '.txt', '.md', '.json', '.csv'
]);
/* Types that must never be launched through the OS, including files already stored in
   the Library from older versions (which were allowed to import .js/.ts/.html/.css). */
const BLOCKED_OPEN_EXT = new Set([
  '.js', '.ts', '.html', '.htm', '.css', '.mjs', '.cjs', '.jse', '.vbs', '.vbe', '.wsf', '.wsh',
  '.bat', '.cmd', '.ps1', '.exe', '.msi', '.scr', '.com', '.lnk', '.hta', '.jar', '.reg', '.svg'
]);
/* Types generated by the app itself (text only). */
const GENERATED_EXT = new Set(['.csv', '.txt', '.md', '.json', '.xlsx']);
const MIME = {
  '.pdf': 'application/pdf', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg',
  '.gif': 'image/gif', '.webp': 'image/webp', '.txt': 'text/plain', '.md': 'text/markdown',
  '.csv': 'text/csv', '.json': 'application/json',
  '.docx': 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  '.xlsx': 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  '.pptx': 'application/vnd.openxmlformats-officedocument.presentationml.presentation'
};
const HASH_RE = /^[0-9a-f]{64}$/;

function safeName(name) { return String(name || '').replace(/[^a-zA-Z0-9._-]/g, '_').slice(0, 120) || 'file'; }

function hashFile(file) {
  const h = crypto.createHash('sha256');
  const fd = fs.openSync(file, 'r');
  try {
    const buf = Buffer.alloc(64 * 1024);
    let pos = 0;
    for (;;) {
      const n = fs.readSync(fd, buf, 0, buf.length, pos);
      if (n === 0) break;
      h.update(buf.subarray(0, n));
      pos += n;
    }
  } finally { fs.closeSync(fd); }
  return h.digest('hex');
}

/**
 * deps: { userDataDir: string, dialog?, shell?, getWindow?: () => BrowserWindow|null }
 */
function createLibraryService(deps) {
  const tokens = new Map();
  const libRoot = () => path.join(deps.userDataDir, 'library');
  function libDir() {
    const d = path.join(libRoot(), 'files');
    if (!fs.existsSync(d)) fs.mkdirSync(d, { recursive: true });
    return d;
  }
  const pendingPath = () => path.join(libRoot(), 'pending-deletions.json');

  function resolve(rel) {
    if (typeof rel !== 'string' || !rel || path.isAbsolute(rel)) return null;
    const base = path.resolve(libDir());
    const full = path.resolve(base, rel);
    if (full !== base && !full.startsWith(base + path.sep)) return null;
    try {
      const realBase = fs.realpathSync(base);
      const realFull = fs.realpathSync(full);
      if (realFull !== realBase && !realFull.startsWith(realBase + path.sep)) return null;
    } catch (e) { /* file may not exist yet */ }
    try { if (fs.lstatSync(full).isSymbolicLink()) return null; } catch (e) { /* missing */ }
    return full;
  }

  function checkSource(src) {
    let st;
    try { st = fs.lstatSync(src); } catch (e) { return { error: 'source-missing' }; }
    if (!st.isFile()) return { error: 'not-file' };
    if (st.size > MAX_BYTES) return { error: 'too-large' };
    const ext = path.extname(src).toLowerCase();
    if (!ALLOWED_EXT.has(ext)) return { error: 'unsupported-type' };
    return { st, ext };
  }

  function sweepTokens() {
    const now = Date.now();
    for (const [k, v] of tokens) if (v.expiresAt < now) tokens.delete(k);
  }

  function addToken(src, st, ext) {
    const token = crypto.randomBytes(16).toString('hex');
    tokens.set(token, { sourcePath: src, originalName: path.basename(src), size: st.size, ext, expiresAt: Date.now() + TOKEN_TTL_MS });
    return { token, originalName: path.basename(src), size: st.size, ext };
  }

  /** req.multiple -> { canceled, files:[{token,...}], errors:[{name,error}] }; otherwise the legacy single-file shape. */
  async function pick(req) {
    req = req && typeof req === 'object' ? req : {};
    const multiple = req.multiple === true;
    sweepTokens();
    const win = deps.getWindow ? deps.getWindow() : null;
    const props = multiple ? ['openFile', 'multiSelections'] : ['openFile'];
    const r = await deps.dialog.showOpenDialog(win, { properties: props, title: multiple ? 'Pilih file output' : 'Pilih file untuk Library' });
    if (r.canceled || !r.filePaths || !r.filePaths.length) return { canceled: true };
    if (!multiple) {
      const c = checkSource(r.filePaths[0]);
      if (c.error) return { canceled: false, error: c.error };
      return Object.assign({ canceled: false }, addToken(r.filePaths[0], c.st, c.ext));
    }
    const files = [], errors = [];
    r.filePaths.slice(0, MAX_PICK).forEach((src) => {
      const c = checkSource(src);
      if (c.error) errors.push({ name: path.basename(src), error: c.error });
      else files.push(addToken(src, c.st, c.ext));
    });
    if (r.filePaths.length > MAX_PICK) errors.push({ name: '', error: 'too-many' });
    return { canceled: false, files, errors };
  }

  /** Finds an existing managed file with the same content (renderer hints are re-verified on disk). */
  function findReusable(hash, size, reuse) {
    if (!Array.isArray(reuse)) return null;
    for (const c of reuse.slice(0, 500)) {
      if (!c || c.hash !== hash || typeof c.fileName !== 'string') continue;
      const full = resolve(c.fileName);
      if (!full) continue;
      try {
        const st = fs.lstatSync(full);
        if (!st.isFile() || st.isSymbolicLink() || st.size !== size) continue;
        if (hashFile(full) === hash) return c.fileName;
      } catch (e) { /* skip */ }
    }
    return null;
  }

  function copyInto(src, dest, expectedSize) {
    const tmp = dest + '.tmp';
    try {
      const srcFd = fs.openSync(src, 'r');
      let tmpFd;
      try {
        tmpFd = fs.openSync(tmp, 'wx');
        const buf = Buffer.alloc(64 * 1024);
        let pos = 0;
        for (;;) {
          const b = fs.readSync(srcFd, buf, 0, buf.length, pos);
          if (b === 0) break;
          fs.writeSync(tmpFd, buf, 0, b);
          pos += b;
        }
      } finally {
        fs.closeSync(srcFd);
        if (tmpFd !== undefined) fs.closeSync(tmpFd);
      }
      const t = fs.statSync(tmp);
      if (!t.isFile() || t.size !== expectedSize) { try { fs.unlinkSync(tmp); } catch (x) { /* */ } return false; }
      fs.renameSync(tmp, dest);
      return true;
    } catch (e) { try { fs.unlinkSync(tmp); } catch (x) { /* */ } return false; }
  }

  function result(fileName, originalName, size, ext, hash, reused) {
    return { ok: true, fileName, id: fileName.split('_').slice(0, 2).join('_'), originalName, size, ext, hash, mimeType: MIME[ext] || null, reused: !!reused };
  }

  async function importFile(req) {
    req = req && typeof req === 'object' ? req : {};
    const entry = tokens.get(req.token);
    if (!entry) return { ok: false, reason: 'bad-token' };
    tokens.delete(req.token);
    if (entry.expiresAt < Date.now()) return { ok: false, reason: 'token-expired' };
    const c = checkSource(entry.sourcePath);
    if (c.error) return { ok: false, reason: c.error };
    let hash;
    try { hash = hashFile(entry.sourcePath); } catch (e) { return { ok: false, reason: 'copy-failed' }; }
    const reusable = findReusable(hash, c.st.size, req.reuse);
    if (reusable) return result(reusable, entry.originalName, c.st.size, c.ext, hash, true);
    const id = 'libfile_' + crypto.randomBytes(8).toString('hex');
    const managedName = id + '_' + safeName(path.basename(entry.sourcePath));
    if (!copyInto(entry.sourcePath, path.join(libDir(), managedName), c.st.size)) return { ok: false, reason: 'copy-failed' };
    return result(managedName, entry.originalName, c.st.size, c.ext, hash, false);
  }

  /** Stores text the app generated itself (e.g. an exported report or note). */
  async function storeGenerated(req) {
    req = req && typeof req === 'object' ? req : {};
    if (typeof req.name !== 'string') return { ok: false, reason: 'bad-input' };
    const ext = path.extname(req.name).toLowerCase();
    if (!GENERATED_EXT.has(ext)) return { ok: false, reason: 'unsupported-type' };
    let bytes;
    if (typeof req.text === 'string') bytes = Buffer.from(req.text, 'utf8');
    else if (ArrayBuffer.isView(req.bytes)) bytes = Buffer.from(req.bytes.buffer, req.bytes.byteOffset, req.bytes.byteLength);
    else if (Object.prototype.toString.call(req.bytes) === '[object ArrayBuffer]') bytes = Buffer.from(new Uint8Array(req.bytes));
    else return { ok: false, reason: 'bad-input' };
    if (ext === '.xlsx' && !(bytes.length > 4 && bytes[0] === 0x50 && bytes[1] === 0x4b)) return { ok: false, reason: 'bad-input' };   // must be a zip container
    if (bytes.length > MAX_BYTES) return { ok: false, reason: 'too-large' };
    const hash = crypto.createHash('sha256').update(bytes).digest('hex');
    const originalName = safeName(path.basename(req.name));
    const reusable = findReusable(hash, bytes.length, req.reuse);
    if (reusable) return result(reusable, originalName, bytes.length, ext, hash, true);
    const id = 'libfile_' + crypto.randomBytes(8).toString('hex');
    const managedName = id + '_' + originalName;
    const dest = path.join(libDir(), managedName);
    const tmp = dest + '.tmp';
    try {
      fs.writeFileSync(tmp, bytes, { flag: 'wx' });
      fs.renameSync(tmp, dest);
    } catch (e) { try { fs.unlinkSync(tmp); } catch (x) { /* */ } return { ok: false, reason: 'copy-failed' }; }
    return result(managedName, originalName, bytes.length, ext, hash, false);
  }

  async function open(req) {
    req = req || {};
    const full = resolve(req.fileName);
    if (!full) return { ok: false, reason: 'bad-path' };
    let st;
    try { st = fs.lstatSync(full); } catch (e) { return { ok: false, reason: 'missing' }; }
    if (st.isSymbolicLink() || !st.isFile()) return { ok: false, reason: 'not-file' };
    if (BLOCKED_OPEN_EXT.has(path.extname(full).toLowerCase())) {
      // Legacy file: never launch it. Show it in its folder instead so the user stays in control.
      try { if (deps.shell.showItemInFolder) deps.shell.showItemInFolder(full); } catch (e) { /* best effort */ }
      return { ok: false, reason: 'blocked-type' };
    }
    const err = await deps.shell.openPath(full);
    if (err) return { ok: false, reason: 'open-failed', message: err };
    return { ok: true };
  }

  function readPending() { try { const v = JSON.parse(fs.readFileSync(pendingPath(), 'utf8')); return Array.isArray(v) ? v : []; } catch (e) { return []; } }
  function writePending(list) { try { fs.mkdirSync(libRoot(), { recursive: true }); fs.writeFileSync(pendingPath(), JSON.stringify(list)); } catch (e) { /* best effort */ } }

  async function deleteFile(req) {
    req = req || {};
    const full = resolve(req.fileName);
    if (!full) return { ok: false, reason: 'bad-path' };
    try {
      const st = fs.lstatSync(full);
      if (st.isSymbolicLink() || !st.isFile()) return { ok: false, reason: 'not-file' };
    } catch (e) { return { ok: true, alreadyMissing: true }; }
    const pending = readPending();
    if (!pending.includes(req.fileName)) { pending.push(req.fileName); writePending(pending); }
    try { fs.unlinkSync(full); } catch (e) { return { ok: false, reason: 'delete-failed' }; }
    writePending(readPending().filter((n) => n !== req.fileName));
    return { ok: true };
  }

  function recoverPending() {
    const list = readPending();
    const remaining = [], deleted = [];
    for (const name of list) {
      const full = resolve(name);
      if (!full) continue;
      try {
        const st = fs.lstatSync(full);
        if (st.isSymbolicLink() || !st.isFile()) { remaining.push(name); continue; }
      } catch (e) { continue; }
      try { fs.unlinkSync(full); deleted.push(name); } catch (e) { remaining.push(name); }
    }
    writePending(remaining);
    return { processed: list.length, remaining: remaining.length, deleted };
  }

  async function cleanupPending(req) {
    const list = Array.isArray(req && req.fileNames) ? req.fileNames : [];
    const out = [];
    for (const name of list) {
      const full = resolve(name);
      if (!full) { out.push({ fileName: name, ok: false, reason: 'bad-path' }); continue; }
      try {
        const st = fs.lstatSync(full);
        if (st.isSymbolicLink() || !st.isFile()) { out.push({ fileName: name, ok: false, reason: 'not-file' }); continue; }
      } catch (e) { out.push({ fileName: name, ok: true, alreadyMissing: true }); continue; }
      try { fs.unlinkSync(full); out.push({ fileName: name, ok: true }); } catch (e) { out.push({ fileName: name, ok: false, reason: 'delete-failed' }); }
    }
    return { ok: true, results: out };
  }

  async function checkFiles(req) {
    const list = Array.isArray(req && req.fileNames) ? req.fileNames.slice(0, 2000) : [];
    const out = {};
    for (const name of list) {
      if (typeof name !== 'string') continue;
      const full = resolve(name);
      if (!full) { out[name] = { exists: false, reason: 'bad-path' }; continue; }
      try {
        const st = fs.lstatSync(full);
        if (st.isSymbolicLink()) { out[name] = { exists: false, reason: 'symlink' }; continue; }
        out[name] = { exists: st.isFile(), regular: st.isFile() };
      } catch (e) { out[name] = { exists: false, reason: 'missing' }; }
    }
    return { ok: true, files: out };
  }

  return { pick, importFile, storeGenerated, open, deleteFile, recoverPending, cleanupPending, checkFiles, _resolve: resolve, _tokens: tokens };
}

module.exports = { createLibraryService, ALLOWED_EXT, BLOCKED_OPEN_EXT, MAX_BYTES, HASH_RE };
